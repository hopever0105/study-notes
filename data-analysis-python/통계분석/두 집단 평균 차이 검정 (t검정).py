

# %% 1. 가설검정의 개념
# (1) 가설검정의 요소
"""
1) 귀무가설 (H0)
   - "차이가 없다, 효과가 없다"는 기본 주장. 검정은 이걸 의심하는 데서 시작한다.
   - 예: A사 평균 체결 지연 = 136ms

2) 대립가설 (H1)
   - 내가 보이고 싶은 주장. "차이가 있다".
   - 예: A사 평균 체결 지연 ≠ 136ms (양측) / > 136ms (단측)

3) 검정통계량
   - 표본이 귀무가설에서 얼마나 멀리 떨어졌는지를 숫자 하나로 바꾼 값.
   - 예: t = (표본평균 - 136) / 표준오차. 0에서 멀수록 귀무가설과 안 맞음.

4) p-value (유의확률)
   - 귀무가설이 맞다고 칠 때, 지금만큼(또는 더) 극단적인 결과가 나올 확률.
   - p-value가 작을수록 기각 가능성 높아짐
   - 예: 동전이 공정하다(H0)고 칠 때 10번 중 9번 이상 한쪽이 나올 확률 = 0.021
         → 공정한 동전으로는 드문 일 → 동전이 공정하지 않다고 의심.
"""

# %% (2) 가설검정 핵심 지표
"""
1) 유의수준 (α, significance level)
   - "이 정도로 드물면 귀무가설을 버리겠다"는 기준. 검정 전에 정한다.
   - 보통 0.05 (5%). 엄격하게는 0.01.

2) p-value (유의확률)
   - 데이터로 계산한 값. α와 비교한다.
   - p < α  → 귀무가설 기각 (차이가 있다)
   - p ≥ α  → 귀무가설 기각 못 함 (차이가 있다고 말할 근거 부족)
     ※ "귀무가설이 맞다"는 뜻이 아님. 증거가 부족할 뿐.
"""

# %% (3) 임계값과 기각역
"""
1) 임계값 (critical value)
   - 유의수준에 따라 결정되는 기준값 
   - 검정통계량이 이 값을 넘으면 기각하는 경계선. α로 정해진다.
   - 예: α = 0.05 양측, 정규분포 → ±1.96 / 단측 → 1.645
         t분포(자유도 9) 양측 → ±2.262

2) 기각역 (rejection region)
   - 임계값 바깥 구간. 검정통계량이 임계값을 넘어서는 영역으로 해당하면  귀무가설 기각.
   - 예: 자유도 9, 양측이면 t < -2.262 또는 t > 2.262
   - "검정통계량이 기각역에 있다" = "p < α" (같은 판단을 두 방식으로 표현)
"""

# %% 2. 가설검정의 수행과 해석
# (1) 가설검정 절차
"""
1) 가설 설정      H0: μ = 136,  H1: μ ≠ 136  등 귀무가설과 대립가설 정의 
2) 유의수준 확인  α = 0.05
3) 검정통계량 및 p-value 산출
                  표본 10개, 평균 140, 표준편차 5
                  t = (140 - 136) / (5 / √10) = 4 / 1.581 = 2.53
                  p = 0.032
4) 기각 여부 결정 p 0.032 < α 0.05  (또는 t 2.53 > 임계값 2.262) → 기각
5) 결론 도출      "A사 평균 체결 지연은 136ms와 다르다 (유의수준 5%)"
"""

# %% (2) 주요 통계적 오류
"""
                    실제 H0 참           실제 H0 거짓
  H0 기각          제1종 오류 (α)        올바름 (검정력 1-β)
  H0 기각 못 함    올바름                제2종 오류 (β)

1) 제1종 오류 (α)
   - 차이가 없는데 있다고 판단. "헛경보". 무죄인 사람(참) 유죄라고 판결함(거짓)
   - 예: 효과 없는 전략을 효과 있다고 채택.
   - α = 0.05면 이런 실수를 5%까지 허용한다는 뜻.
   - 퀀트에서 중요: 효과 없는 전략 100개를 검정하면 우연히 약 5개가 "유의"하게 나옴
     (다중검정 문제).

2) 제2종 오류 (β)
   - 차이가 있는데 없다고 판단. "놓침". 유죄인 사람(거짓) 무죄라고 판결 즉 풀어줌(참)
   - 예: 실제로 돈 버는 전략을 버림.
   - 표본이 작을수록 커진다. 1 - β = 검정력(차이를 잡아낼 확률).
   - α를 줄이면 β는 커진다 (둘은 시소 관계).
"""

# %% ===== 4절 평균의 비교 =====
# %% 1. 평균 비교 분석 로드맵
"""
비교 대상              예시                          모수 (정규성 충족)            비모수 (정규성 미충족)
---------------------  ----------------------------  ----------------------------  ------------------------------
1개 집단               A사 평균 지연이 136ms인가?     일표본 t검정                  Wilcoxon 부호순위 검정
                                                     stats.ttest_1samp             stats.wilcoxon(x - 136)
2개 집단 (독립)        A사 vs B사                     독립표본 t검정                Mann-Whitney U 검정
                                                     stats.ttest_ind               stats.mannwhitneyu
1개 집단 2개 시점      같은 종목, 시스템 개선 전 vs 후  대응표본 t검정                Wilcoxon 부호순위 검정
(대응)                                               stats.ttest_rel               stats.wilcoxon
3개 이상 집단          A사 vs B사 vs C사              분산분석 (ANOVA)              Kruskal-Wallis 검정
                                                     stats.f_oneway                stats.kruskal
"""

# %% 2. t-test 개념
# (1) 상황 예시
"""
- 모집단 표준편차를 모르고, 표본으로 평균을 비교할 때 쓴다.
- 예: A사 체결 지연 10건만 재봤다. 평균 140ms. 기준 136ms보다 정말 느린 걸까,
      우연히 느린 표본이 뽑힌 걸까?
- 표본이 작으면 정규분포 대신 꼬리가 두꺼운 t분포를 쓴다 (불확실성 반영).
  자유도가 커질수록(표본이 많을수록) t분포는 정규분포에 가까워진다.
"""

# %% (2) t 통계량 계산 방법
"""
핵심 모양:  t = (관측한 차이) / (그 차이의 표준오차)
           = "차이가 우연한 흔들림의 몇 배인가"

1) 표본 1개일 때 (일표본)
   t = (x̄ - μ0) / (s / √n),   자유도 = n - 1
   예: x̄ = 140, μ0 = 136, s = 5, n = 10
       t = 4 / (5 / 3.162) = 4 / 1.581 = 2.53

2) 표본 2개일 때 (독립표본)
   - 등분산 가정 (Student):
     sp² = [(n1 - 1)s1² + (n2 - 1)s2²] / (n1 + n2 - 2)
     t = (x̄1 - x̄2) / ( sp × √(1/n1 + 1/n2) ),   자유도 = n1 + n2 - 2
     예: x̄1 = 140, x̄2 = 135, s1 = s2 = 5, n1 = n2 = 10
         sp = 5,  t = 5 / (5 × √0.2) = 5 / 2.236 = 2.24,  p = 0.038
   - 이분산 (Welch):
     t = (x̄1 - x̄2) / √(s1²/n1 + s2²/n2)   (자유도는 별도 공식, 함수가 계산)

   (대응표본은 전후 차이 d를 구해 일표본처럼 계산)
     t = d̄ / (s_d / √n)
     예: 10개 종목 전후 차이 평균 -7.8, 차이의 표준편차 0.79
         t = -7.8 / (0.79 / 3.162) = -31.3
"""

# %% (3) t-test 유형
"""
1) 일표본 t검정     한 집단 평균 vs 정해진 기준값      (A사 평균 vs 136ms)
2) 독립표본 t검정   서로 다른 두 집단 평균              (A사 vs B사)
3) 대응표본 t검정   같은 대상의 전후 평균               (같은 종목, 개선 전 vs 후)
4) 분산분석         세 집단 이상 평균 → t검정을 여러 번 하면 제1종 오류가 쌓이므로
                    한 번에 비교 (다음 절)
"""

# %% 3. 일표본 t검정
# (1) 개념
"""
1) 분석 목적
   - 한 집단의 평균이 특정 기준값과 같은지 확인.
   - 예: A사 평균 체결 지연이 공시한 136ms와 같은가?

2) 필수 가정
   - 정규성: 데이터가 정규분포를 따른다 (Shapiro-Wilk로 확인).
             n ≥ 30이면 중심극한정리로 평균의 분포가 정규에 가까워져 덜 엄격.
   - 독립성: 관측값끼리 서로 영향 없음 (한 주문의 지연이 다음 주문에 영향 X).
"""

# %% (2) 분석 단계
"""
1) 가설 수립     H0: μ = 136,  H1: μ ≠ 136
2) 유의수준 설정 α = 0.05
3) 정규성 검정   stats.shapiro(x) → p ≥ 0.05면 정규성 OK
4) 모델 선택 및 결과 산출
                 정규성 OK  → stats.ttest_1samp(x, popmean=136)
                 정규성 X   → stats.wilcoxon(x - 136)
5) 결과 해석     p < 0.05 → "평균은 136ms와 다르다"
                 p ≥ 0.05 → "136ms와 다르다고 할 근거 없음"
"""

# %% 4. 독립표본 t검정
# (1) 개념
"""
1) 분석 목적
   - 서로 다른 두 집단의 평균이 같은지 확인.
   - 예: A사와 B사의 평균 체결 지연이 같은가?

2) 필수 가정
   - 정규성: 두 집단 각각 정규분포 (각각 Shapiro-Wilk).
   - 독립성: 두 집단은 서로 다른 대상 (A사 주문과 B사 주문은 별개).
   - 등분산성: 두 집단의 분산이 같은지 (Levene로 확인) → 결과에 따라 공식이 갈림.
"""

# %% (2) 분석 단계
"""
1) 가설 수립     H0: μA = μB,  H1: μA ≠ μB
2) 유의수준 설정 α = 0.05
3) 정규성 검정   stats.shapiro(a), stats.shapiro(b)
   + 등분산 검정 stats.levene(a, b) → p ≥ 0.05면 분산 같음
4) 모델 선택 및 결과 산출
                 정규 O, 등분산 O → stats.ttest_ind(a, b, equal_var=True)   (Student)
                 정규 O, 등분산 X → stats.ttest_ind(a, b, equal_var=False)  (Welch)
                 정규 X           → stats.mannwhitneyu(a, b, alternative='two-sided')
5) 결과 해석     p < 0.05 → "두 증권사 평균 체결 지연은 다르다"
                 p ≥ 0.05 → "다르다고 할 근거 없음"
"""

# %% 5. 대응표본 t검정
# (1) 개념
"""
1) 분석 목적
   - 같은 대상을 두 번 잰 값(전후)의 평균 차이가 0인지 확인.
   - 예: 같은 10개 종목에서 시스템 개선 전후 체결 지연이 달라졌나?
   - 독립표본과 차이: 같은 종목끼리 짝을 지어 '차이'만 보므로,
     종목마다 원래 빠르고 느린 차이가 지워져 더 정확하다.

2) 필수 가정
   - 정규성: 원래 값이 아니라 '전후 차이(d)'가 정규분포.
   - 독립성: 짝(종목)끼리는 서로 독립.

3) 비모수 검정
   - 정규성 가정이 깨졌을 때 쓰는 검정. 값 대신 '순위'로 계산한다.
   - 장점: 이상값에 강함 (지연 2,000ms 같은 튀는 값 하나에 덜 흔들림).
   - 단점: 정규성이 맞을 때는 t검정보다 차이를 잡아내는 힘(검정력)이 약함.
"""

# %% (2) 비모수 검정 선택 기준
"""
언제: 정규성 검정 p < 0.05 이고 표본이 작을 때 (대략 n < 30),
      이상값이 많을 때, 순위·등급 데이터일 때

  상황         모수 검정           →  비모수 검정
  독립표본     독립표본 t검정      →  Mann-Whitney U 검정   stats.mannwhitneyu(a, b)
  대응표본     대응표본 t검정      →  Wilcoxon 부호순위 검정 stats.wilcoxon(after, before)
"""

# %% (3) 분석 단계
"""
1) 가설 수립     H0: 전후 차이 평균 = 0,  H1: ≠ 0
2) 유의수준 설정 α = 0.05
3) 정규성 검정   diff = after - before → stats.shapiro(diff)
4) 모델 선택 및 결과 산출
                 정규 O → stats.ttest_rel(after, before)
                 정규 X → stats.wilcoxon(after, before, alternative='two-sided')
5) 결과 해석     p < 0.05 → "개선 전후 체결 지연이 달라졌다"
                 (차이 평균이 음수면 줄어든 것)
"""
#%% 
# -*- coding: utf-8 -*-
# 두 집단 평균 차이 검정 (t검정)
# 상황: 증권사 A·B의 주문 체결 지연시간(밀리초)을 비교한다.
# 데이터: 연습용으로 직접 만든 값 (난수 고정 → 누가 돌려도 같은 결과)

#%% 
# -*- coding: utf-8 -*-
# 가설검정과 평균 비교 (t검정)
# 예시 상황: 증권사 주문 체결 지연시간(밀리초, ms)
# %% 0. 연습 데이터 만들기
import numpy as np
import pandas as pd
import scipy.stats as stats

rng = np.random.default_rng(42)
# 체결 지연은 대부분 빠르고 가끔 크게 늦어지는 '오른쪽 꼬리' 모양 → 로그정규분포로 만듦
a_ms = rng.lognormal(mean=np.log(135), sigma=0.25, size=80)
b_ms = rng.lognormal(mean=np.log(150), sigma=0.25, size=80)

df = pd.DataFrame({
    'broker': ['A'] * 80 + ['B'] * 80,
    'fill_ms': np.round(np.concatenate([a_ms, b_ms]), 1),
})
print(df.head())

# %% 1. 단일표본: A사 평균 체결 지연이 기준 136ms와 다른가?
a_fill = df[df['broker'] == 'A']['fill_ms']

# 정규성 검정 (Shapiro-Wilk)
# 귀무가설: "데이터가 정규분포를 따른다"
stat, p_norm = stats.shapiro(a_fill)
print(f"정규성 검정 p-value: {p_norm:.4f}")
# 결과 0.2261 > 0.05 → 정규성 OK → t검정 써도 됨

# %%
# 기준값 my를 136으로 설정하여 검정 수행 
mu_0 = 136
t_stat, p_value = stats.ttest_1samp(a_fill, popmean=mu_0)
print(f"검정통계량(t): {t_stat:.4f}")
print(f"p-value: {p_value:.4f}")
# 결과 p = 0.4250 > 0.05 → "A사 평균은 136ms와 다르다"고 말할 근거 없음
# 즉, 유의한 차이 없다. 

# %% 2. 독립표본: A사와 B사의 체결 지연이 다른가?
a_fill = df[df['broker'] == 'A']['fill_ms']
b_fill = df[df['broker'] == 'B']['fill_ms']

# 정규성 검정 (Shapiro-Wilk)
print("A사 정규성 p-value:", stats.shapiro(a_fill).pvalue)
print("B사 정규성 p-value:", stats.shapiro(b_fill).pvalue) # B는 정규분포아니다. 
# 결과 A 0.226 / B 0.00004 → B는 정규성 깨짐

# 등분산성 검정 (Levene)
# 귀무가설: "두 집단의 분산은 같다."
stat, p_levene = stats.levene(a_fill, b_fill)
print(f"등분산성 검정 p-value: {p_levene:.4f}")
# 0,0727인바 분산이 같다고 본다. 


# %%
# 정규성이 깨졌으므로 B사는  Mann-Whitney U 검정 실시
u_stat, p_val = stats.mannwhitneyu(a_fill, b_fill, alternative='two-sided')
print(f"검정통계량(U): {u_stat:.4f}")
print(f"p-value: {p_val:.4f}")
# 결과 p = 0.1675 > 0.05 → 두 증권사 체결 지연이 다르다고 말할 근거 없음

# %% 3. 대응표본: 주문 시스템 개선 전후, 같은 10개 종목의 체결 지연이 줄었나?
data = {
    'before_ms': [135, 140, 138, 142, 137, 139, 141, 136, 143, 138],
    'after_ms':  [128, 132, 129, 135, 130, 131, 133, 127, 136, 130],
}
df_paired = pd.DataFrame(data, index=['삼성전자', 'SK하이닉스', 'LG에너지솔루션', '삼성바이오로직스',
                                      '현대차', '기아', '셀트리온', 'KB금융', 'NAVER', '신한지주'])

# 전후 차이 계산
diff = df_paired['after_ms'] - df_paired['before_ms']

# 정규성 검정 (Shapiro-Wilk)
stat, p_norm = stats.shapiro(diff)
print(f"차이값의 정규성 p-value: {p_norm:.4f}")
# 결과 0.0251 < 0.05 → 정규성 깨짐 → 대응표본 t검정 대신 Wilcoxon
# shaprio는 정규분포를 따른다임을 주의  

# %%
# 비모수 검정 (Wilcoxon Signed-Rank Test) 실시
# 정규성 만족하지 않는 바 ttest_rel 사용 x 
# 두 집단 데이터를 직접 넣거나, 차이값(diff)을 넣어도 됩니다.
result = stats.wilcoxon(df_paired['after_ms'], df_paired['before_ms'], alternative='two-sided')
print(f"검정통계량: {result.statistic}")
print(f"p-value: {result.pvalue:.4f}")
# 결과 p = 0.0020 < 0.05 → 개선 후 체결 지연이 달라졌다(줄었다)
# 즉 귀무가설 기각하여 유의미한 차이가 존재한다로 결론냄. 