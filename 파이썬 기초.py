# ==========================================
# A.3 고급 자료형 (리스트, 세트, 튜플, 딕셔너리)
# ==========================================
# 1. 리스트 (List): 대괄호 [] 사용, 값 추가/삭제 가능
prices = [100, 200, 300, 400, 500][cite: 147]
prices.append(600)      # 값 추가[cite: 147]
prices.remove(400)      # 값 제거[cite: 147]
prices.extend([700, 200]) # 여러 값 추가[cite: 148]

# 2. 세트 (Set): 중괄호 {} 사용, 수학의 집합 개념 (합집합 |, 교집합 &, 차집합 -)[cite: 148]
A_set = {1, 2, 3, 4, 5}[cite: 148]
B_set = {4, 5, 6, 7, 8}[cite: 148]
print(A_set | B_set)    # 합집합[cite: 148]
print(A_set & B_set)    # 교집합[cite: 148]
print(A_set - B_set)    # 차집합[cite: 148]

# 3. 튜플 (Tuple): 소괄호 () 사용, 생성 후 데이터 변경 불가[cite: 149]
t = (1, 2, 3)[cite: 149]

# 4. 딕셔너리 (Dictionary): 'key: value' 형태, 중괄호 {} 사용[cite: 149]
d = {'Kim': 123, 'Lee': 456}[cite: 149]
d['Choi'] = 789         # 데이터 추가[cite: 149]
del d['Lee']            # 데이터 삭제[cite: 149]


# ==========================================
# A.4 반복문 (for)
# ==========================================
# - 정해진 구간을 순차적으로 순회[cite: 150]
for p_val in prices:
    print('가격은 ', p_val, '입니다.')[cite: 151]


