#%%
# ① 리스트에서 "바로 앞 값"과 비교하기  → 문제 1(오른 날 세기)에 씀
# ------------------------------------------------------------
vol = [10, 30, 20, 50]   # 날짜순 거래량. vol[0]=10, vol[1]=30, vol[2]=20, vol[3]=50
                         # 리스트 번호(인덱스)는 0부터 시작합니다.

print(len(vol))          # 4 → len()은 리스트에 든 값의 개수

#%% 
# range(1, len(vol)) 은 1, 2, 3 을 차례로 만듭니다.
#   - 1에서 시작: 0번째 날은 "전날"이 없어서 비교할 수 없으니 건너뜀
#   - len(vol)=4 바로 앞 숫자인 3에서 끝: 끝 숫자 4는 포함하지 않음

for i in range(1,len(vol)):
    today = vol[i]
    yesterday = vol[i-1]
    print("i =", i, "| 오늘", today, "| 전날", yesterday, "| 차이", today - yesterday)
# 출력:
# i = 1 | 오늘 30 | 전날 10 | 차이 20
# i = 2 | 오늘 20 | 전날 30 | 차이 -10
# i = 3 | 오늘 50 | 전날 20 | 차이 30

#%%조건에 맞는 것 "개수 세기" 기본형:
#   count = 0 으로 시작 → 조건이 맞을 때마다 count += 1 (1씩 더하기)
count = 0
for i in range(1, len(vol)):
    if vol[i] - vol[i-1] >= 20:   # 전날보다 20 이상 늘어난 날만
        count = count + 1                # count = count + 1 과 같은 뜻
print("20 이상 늘어난 날:", count)  # 2 (i=1, i=3)


