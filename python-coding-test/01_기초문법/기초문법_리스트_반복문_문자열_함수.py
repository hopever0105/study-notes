# %% ------------------------------------------------------------
# ⑤ def solution — "solution이라는 이름의 함수(기계)를 만든다"
# ---------------------------------------------------------------
# 함수 = 값을 넣으면(입력) 일을 하고 결과를 돌려주는(출력) 기계
#   def       → "함수를 정의(define)하겠다"는 선언. 이건 진짜 파이썬 명령어
#   solution  → 함수 이름. total처럼 지은 이름. 프로그래머스 채점기가
#               solution이라는 이름으로 불러서 채점하기 때문에 문제에서 이 이름을 쓰라고 정한 것
#   (prices)  → 기계에 넣을 입력을 받는 자리. 이것도 지은 이름
#   :         → 여기부터 기계 내용 시작. 아래 줄들은 들여쓰기(4칸)를 해야 함수 안으로 인정됨
#   return    → 기계가 결과를 밖으로 돌려주는 명령어. return을 만나면 함수가 끝남

# 아주 쉬운 예: 숫자 두 개를 받아 더해서 돌려주는 기계
def add(a, b):          # add라는 기계, 입력 자리 a와 b
    result = a + b      # 기계 안에서 하는 일
    return result       # 결과를 밖으로 내보냄

print(add(3, 5))        # 8  ← add에 3과 5를 넣고 나온 결과를 출력
print(add(10, -2))      # 8

# 수익률 계산기 예: 산 가격, 판 가격을 넣으면 수익률(%)을 돌려줌
def ret(buy, sell):
    return (sell - buy) / buy * 100

print(ret(100, 110))    # 10.0
print(ret(100, 95))     # -5.0

# def만 써 두면 기계를 "만들어 놓기만" 한 상태라 아무 일도 안 일어난다.
# 이름(입력) 으로 "불러야" 실행된다 → 그래서 문제 틀 맨 아래에 print(solution(...))가 있는 것
