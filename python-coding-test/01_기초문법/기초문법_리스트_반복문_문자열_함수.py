# %% ------------------------------------------------------------
# ① f"{n:05d}" 읽는 법 — 한 글자씩 뜯어보기
# ---------------------------------------------------------------
n = 42

# f"  ...  "   → 앞에 f가 붙은 문자열. "중괄호 { } 안에 변수를 끼워 넣겠다"는 뜻
print(f"오늘 종가는 {n}원")      # 오늘 종가는 42원  ← {n} 자리에 42가 들어감
print("오늘 종가는 {n}원")       # 오늘 종가는 {n}원 ← f가 없으면 글자 그대로 나옴

# {n:05d} 는 콜론(:)을 기준으로 둘로 나눠 읽는다
#   n   → 무엇을 넣을지: 변수 n
#   :   → 여기부터 "어떤 모양으로" 넣을지 지시
#   0   → 빈자리를 0으로 채워라 (안 쓰면 빈칸으로 채움)
#   5   → 전체 폭을 5칸으로 맞춰라
#   d   → n을 정수(decimal, 10진수)로 써라
# 소리 내어 읽으면: "n을, 정수로, 5칸에 맞춰, 빈자리는 0으로"
print(f"{n:05d}")    # 00042  (42는 2칸 → 남은 3칸을 0으로)
print(f"{n:5d}")     #    42  (0을 빼면 빈칸으로 채움 → 앞에 공백 3개)
print(f"{n:08d}")    # 00000042  (8칸으로)
print(f"{n:03d}")    # 042


