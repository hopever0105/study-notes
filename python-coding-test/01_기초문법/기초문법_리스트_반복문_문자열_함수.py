# ------------------------------------------------------------
# ④ 첫 글자 떼기, 나머지를 숫자로 바꾸기  → 문제 3에 씀
# ------------------------------------------------------------
p = "K12"

print(p[0])              # "K"  → [0]은 첫 글자
print(p[1:])             # "12" → [1:]은 두 번째 글자부터 끝까지. 아직은 "글자"
print(p[1:] + "5")       # "125" → 글자끼리 더하면 이어 붙여짐(계산이 아님!)
print(int(p[1:]) + 5)    # 17  → int()로 숫자로 바꿔야 진짜 덧셈이 됨

#%% 첫 글자에 따라 다르게 처리하기: if / else
total = 0
for p in "A3,K12,A1".split(","):
    letter = p[0]            # 첫 글자
    number = int(p[1:])      # 나머지를 숫자로
    if letter == "A":        # == 는 "같은가?" 비교 (= 하나는 값 넣기라서 다름)
        total = total+number      # A면 더하기
    else:
        total = total- number      # 나머지(K)면 빼기
    print(p, "→", letter, number, "| 지금까지 합계", total)
print("최종:", total)        # 3 - 12 + 1 = -8



