#------------------------------------------------------------
# ② 숫자 → 앞에 0을 채운 문자열  → 문제 2(종목코드 6자리)에 씀
# ------------------------------------------------------------
n = 42
print(str(n))            # "42" → str()은 숫자를 글자로 바꿈. 0 채우기는 글자에만 할 수 있음
print(str(n).zfill(5))   # "00042" → zfill(5): 전체가 5자리가 될 때까지 앞을 0으로 채움
print(str(12345).zfill(5))  # "12345" → 이미 5자리면 그대로
