# 문법: 올림(ceil), 몫·나머지, 최소공배수(gcd), 평균
# Spyder에서 F5로 실행

# %% 1. 올림: "모자라면 하나 더" (피자 (1)·(3))
#   주식 25주를 10주 단위로만 살 수 있으면 → 몇 번 주문? 2.5 → 3번
import math
print(math.ceil(25 / 10))    # 3   (ceil = 올림)
print(math.ceil(20 / 10))    # 2   (딱 나누어떨어지면 그대로)

#   math 없이 하는 법: (a + b - 1) // b
print((25 + 10 - 1) // 10)   # 34 // 10 = 3
print((20 + 10 - 1) // 10)   # 29 // 10 = 2

# %% 2. 몫 // 과 나머지 %  (복습)
print(25 // 10)   # 2  (몫)
print(25 % 10)    # 5  (나머지) → 0이 아니면 '딱 안 나눠짐'

# %% 3. 최소공배수: 두 수로 모두 나누어떨어지는 가장 작은 수 (피자 (2))
#   4일마다 리밸런싱, 6일마다 배당 확인 → 둘이 같은 날 겹치는 첫날은? 12일
a, b = 4, 6
g = math.gcd(a, b)          # 최대공약수 2  (괄호에 재료 a, b 꼭 넣기!)
print(a * b // g)           # 24 // 2 = 12  ← 최소공배수 공식

#   while로 직접 찾는 법: 4, 8, 12 … 를 6으로 나눠 떨어질 때까지
x = a
while x % b != 0:   # 나머지가 0이 아니면 계속
    x += a          # 4 → 8 → 12
print(x)            # 12

# %% 4. 평균: 합 ÷ 개수 (배열의 평균값)
returns = [2, 4, 9]
print(sum(returns))                  # 15
print(len(returns))                  # 3
print(sum(returns) / len(returns))   # 5.0  (/ 는 항상 소수로 나옴)
