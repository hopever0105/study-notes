# 프로그래머스 입문 Day 9 · 모스부호 (1)
# 문제: 공백으로 구분된 모스부호 문자열 letter → 영어 소문자 단어로 바꾸기. 모스부호 표(딕셔너리)는 문제에 주어짐.
# Spyder: F5 전체 실행

# %% 정답
def solution(letter):
    morse = {
        '.-': 'a', '-...': 'b', '-.-.': 'c', '-..': 'd', '.': 'e', '..-.': 'f',
        '--.': 'g', '....': 'h', '..': 'i', '.---': 'j', '-.-': 'k', '.-..': 'l',
        '--': 'm', '-.': 'n', '---': 'o', '.--.': 'p', '--.-': 'q', '.-.': 'r',
        '...': 's', '-': 't', '..-': 'u', '...-': 'v', '.--': 'w', '-..-': 'x',
        '-.--': 'y', '--..': 'z'
    }
    answer = ''
    for code in letter.split(' '):          # '.... . .-.. .-.. ---' → ['....', '.', '.-..', '.-..', '---']
        answer = answer + morse[code]       # 딕셔너리에서 꺼내 한 글자씩 이어 붙이기
    return answer

# %% 확인
print(solution('.... . .-.. .-.. ---'))      # hello
print(solution('.--. -.-- - .... --- -.'))   # python

# %% 포인트
# - 이번엔 split이 필요함: 모스부호 한 글자가 여러 기호('....')라서 공백으로 끊어야 함
#   (반대로 'abc'처럼 한 글자씩이면 for ch in s 로 바로 돎)
