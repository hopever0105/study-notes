# ============================================================
# 분수의 덧셈 — 풀기 전에 알아야 할 것 3가지
#   ① 분수 덧셈 공식   ② 최대공약수(math.gcd)로 약분   ③ / 와 // 차이
# ============================================================


# %% ① 분수 덧셈: 통분 없이 "서로 분모를 곱해서" 더하기
#   a/b + c/d = (a×d + c×b) / (b×d)
#
#   예) 1/6 + 1/3
#     분자 = 1×3 + 1×6 = 3 + 6 = 9
#     분모 = 6×3 = 18
#     → 9/18   (아직 약분 안 됨, 진짜 답은 1/2)
#
#   왜 분모를 그냥 곱하나? 최소공배수(6)를 찾는 것보다 코드가 단순하고,
#   어차피 ②에서 약분하면 같은 답이 나오기 때문
a, b = 1, 6      # 첫 분수 1/6   (a = 분자, b = 분모)
c, d = 1, 3      # 둘째 분수 1/3
top = a * d + c * b
bottom = b * d
print(top, bottom)          # 9 18


# %% ② 약분 = 분자·분모를 "최대공약수"로 나누기
#   최대공약수(GCD) = 두 수를 둘 다 나누어떨어지게 하는 가장 큰 수
#   9의 약수:  1, 3, 9
#   18의 약수: 1, 2, 3, 6, 9, 18
#   공통: 1, 3, 9 → 가장 큰 것 = 9
#   9/18 → (9÷9)/(18÷9) = 1/2   ← 더 이상 약분 안 되는 "기약분수"
#
#   파이썬엔 최대공약수를 구해 주는 기능이 이미 있음: math.gcd
import math                 # 기본 파이썬에 들어 있는 수학 도구 묶음 (설치 필요 없음)
g = math.gcd(9, 18)
print(g)                    # 9
print(math.gcd(12, 8))      # 4   (12/8 → 3/2)
print(math.gcd(7, 5))       # 1   (이미 기약분수 → 1로 나누면 그대로)


# %% ③ 나누기 기호: /  와  //
print(9 / 9)      # 1.0   ← / 는 항상 소수(1.0)로 나옴
print(18 / 9)     # 2.0
print(9 // 9)     # 1     ← // 는 몫만, 정수로 나옴
print(18 // 9)    # 2
# 답은 [1, 2] 여야 하는데 / 를 쓰면 [1.0, 2.0] 이 돼서 채점에서 틀림
# → 약분할 땐 // 를 쓴다 (나누어떨어지는 게 보장되니까 몫 = 정확한 값)


# %% 여기까지 합치면 (예시 1/6 + 1/3)
top = 1 * 3 + 1 * 6          # 9
bottom = 6 * 3               # 18
g = math.gcd(top, bottom)    # 9
print([top // g, bottom // g])   # [1, 2]   ← 리스트에 [분자, 분모] 순서로 담기


# %% ============================================================
# 이제 직접 풀기: 위 "합치기" 4줄을 함수 안에 옮기면 됨
#   numer1 = 첫 분수 분자, denom1 = 첫 분수 분모
#   numer2 = 둘째 분수 분자, denom2 = 둘째 분수 분모
#   return [기약분수 분자, 기약분수 분모]
# ===============================================================
import math

def solution(numer1, denom1, numer2, denom2):
    top = numer1 * denom2 + numer2 * denom1 
    bottom = denom1 * denom2 
    g = math.gcd(top,bottom)
    answer = [top//g, bottom//g]
    return answer

print(solution(1, 2, 3, 4))   # [5, 4]   1/2 + 3/4 = (4 + 6)/8 = 10/8 → gcd 2 → 5/4
print(solution(9, 2, 1, 3))   # [29, 6]  9/2 + 1/3 = (27 + 2)/6 = 29/6 → gcd 1 → 그대로
print(solution(1, 6, 1, 3))   # [1, 2]   위에서 손으로 계산한 예시


