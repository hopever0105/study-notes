# %% [Appendix] 파이썬 프로그래밍 기초 통합 스터디 노트

# ==========================================
# A.1 파이썬 기본 문법
# ==========================================
# - 코드 실행 단축키: Shift + Enter
# - 결과값 출력: 가장 일반적인 출력 방법은 print() 함수 사용
print(1)
print('A')

# - 대소문자 구분: 파이썬은 대소문자를 엄격히 구분하므로 A와 a는 서로 다른 변수
A = '변수1'
a = '변수2'

# - 들여쓰기: 문단을 구분하므로 동일한 위치에서 시작해야 함 (어기면 IndentationError 발생)
print(1)
print(2)

# - 줄바꿈: 문장이 너무 길 경우 백슬래시(\)를 붙이고 다음 줄로 연결
B = '문장을 만들어볼까요?' \
    ' 긴 문장을 한 줄로 만들어볼까요?'

# - 주석: 코딩에 포함되지만 해석되지 않는 문자열. 한 줄은 #, 여러 줄은 ''' 또는 """ 사용
# 이것은 한 줄 주석입니다.
p = 100

# - 변수 형식(자료형): 숫자형(int, float, complex), 문자형(str)
i = 1        # 정수형 (int)
f = 1.0      # 소수형 (float)
c = 1 + 2j   # 복소수형 (complex)
s = '나는 문자' # 문자형 (str)


# ==========================================
# A.2 사치연산 및 문자열 조작
# ==========================================
# - 숫자 사치연산: 더하기(+), 빼기(-), 곱하기(*), 나누기(/), 나머지(%), 거듭제곱(**)
x = 3
print(x * 2)   # 6
print(x ** 2)  # 거듭제곱 (x * x와 같은 표현, 9)

# - 문자열 합치기와 자르기(슬라이싱)
w1 = 'Py'
w2 = 'thon'
word = w1 + w2  # 문자열 합치기 -> 'Python'
print(word[0:2]) # 슬라이싱: 0부터 2 미만까지 추출 -> 'Py'


# ==========================================
# A.3 고급 자료형 (리스트, 세트, 튜플, 딕셔너리)
# ==========================================
# 1. 리스트 (List): 대괄호 [] 사용, 값 추가/삭제 가능
prices = [100, 200, 300, 400, 500]
prices.append(600)      # 값 추가
prices.remove(400)      # 값 제거
prices.extend([700, 200]) # 여러 값 추가

# 2. 세트 (Set): 중괄호 {} 사용, 수학의 집합 개념 (합집합 |, 교집합 &, 차집합 -)
A_set = {1, 2, 3, 4, 5}
B_set = {4, 5, 6, 7, 8}
print(A_set | B_set)    # 합집합
print(A_set & B_set)    # 교집합
print(A_set - B_set)    # 차집합

# 3. 튜플 (Tuple): 소괄호 () 사용, 생성 후 데이터 변경 불가
t = (1, 2, 3)

# 4. 딕셔너리 (Dictionary): 'key: value' 형태, 중괄호 {} 사용
d = {'Kim': 123, 'Lee': 456}
d['Choi'] = 789         # 데이터 추가
del d['Lee']            # 데이터 삭제


# ==========================================
# A.4 반복문 (for)
# ==========================================
# - 정해진 구간을 순차적으로 순회
for p_val in prices:
    print('가격은 ', p_val, '입니다.')


# ==========================================
# A.5 제어문 (if-elif-else)
# ==========================================
# - 조건에 따른 분기 처리
p_input = 11000
if p_input < 10000:
    print('매수')
elif p_input > 10000:
    print('매도')
else:
    print('중립')